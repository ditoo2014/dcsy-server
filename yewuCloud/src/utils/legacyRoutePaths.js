/** 保留旧书签及本地存储地址的入口，实际页面统一使用英文路径。 */
export function normalizeLegacyRoutePath(path) {
  if (typeof path !== 'string') return path
  const key = path.length > 1 ? path.replace(/\/$/, '') : path
  return Object.hasOwn(LEGACY_FRONTEND_PATHS, key) ? LEGACY_FRONTEND_PATHS[key] : path
}
