/**
 * @param {string} path
 * @returns {Boolean}
 */
export function isExternal(path) {
  return /^(https?:|mailto:|tel:)/.test(path)
}

/**
 * @param {string} str
 * @returns {Boolean}
 */
export function testIPV4(ip) { // 传入ip，若为IPV4地址返回true,例如ip为255.255.255.255时返回true
  const ipRegEx = '^([1-9]|([1-9][0-9])|(1[0-9][0-9])|(2[0-4][0-9])|(25[0-5]))(\.([0-9]|([1-9][0-9])|(1[0-9][0-9])|(2[0-4][0-9])|(25[0-5]))){3}$'
  const patt = new RegExp(ipRegEx)
  if (ip === '0.0.0.0') {
    return true
  } else {
    return patt.test(ip)
  }
}

export function checkPhone(phone) { // 验证电话号码
  if (!(/^1[3456789]\d{9}$/.test(phone))) {
    return false
  } else {
    return true
  }
}

