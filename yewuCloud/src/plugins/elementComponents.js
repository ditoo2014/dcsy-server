export function registerElementComponents(app) {
  // 采集云的卡片标题、空状态和导入提示也依赖真实组件，不能当作普通 HTML 标签。
  components.forEach((component) => {
    if (component?.name) {
      app.component(component.name, component)
    }
  })
  app.directive('loading', ElLoading.directive)
}
